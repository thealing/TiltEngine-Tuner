inline uint64_t bishop_tables[64][1 << 9];

inline uint64_t rook_tables[64][1 << 12];

inline uint64_t get_bishop_index(int square, uint64_t mask)
{
	return mask * bishop_multipliers[square] >> 55;
}

inline uint64_t get_rook_index(int square, uint64_t mask)
{
	return mask * rook_multipliers[square] >> 52;
}

inline uint64_t get_bishop_mask(int square, uint64_t occupied_mask)
{
	return bishop_tables[square][get_bishop_index(square, occupied_mask & bishop_masks[square])];
}

inline uint64_t get_rook_mask(int square, uint64_t occupied_mask)
{
	return rook_tables[square][get_rook_index(square, occupied_mask & rook_masks[square])];
}

inline uint64_t get_queen_mask(int square, uint64_t occupied_mask)
{
	return get_bishop_mask(square, occupied_mask) | get_rook_mask(square, occupied_mask);
}

inline bool init_bitmasks()
{
	for (int src_rank = 0; src_rank < 8; src_rank++)
	{
		for (int src_file = 0; src_file < 8; src_file++)
		{
			int src_square = src_rank * 8 + src_file;
			uint64_t mask_mask = bishop_masks[src_square];
			uint64_t sub_mask = mask_mask + 1;
			do
			{
				sub_mask = (sub_mask - 1) & mask_mask;
				uint64_t hash = get_bishop_index(src_square, sub_mask);
				for (int dst_rank = src_rank + 1, dst_file = src_file + 1; dst_rank < 8 && dst_file < 8; dst_rank++, dst_file++)
				{
					int square = dst_rank * 8 + dst_file;
					set_square(bishop_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_rank = src_rank + 1, dst_file = src_file - 1; dst_rank < 8 && dst_file >= 0; dst_rank++, dst_file--)
				{
					int square = dst_rank * 8 + dst_file;
					set_square(bishop_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_rank = src_rank - 1, dst_file = src_file - 1; dst_rank >= 0 && dst_file >= 0; dst_rank--, dst_file--)
				{
					int square = dst_rank * 8 + dst_file;
					set_square(bishop_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_rank = src_rank - 1, dst_file = src_file + 1; dst_rank >= 0 && dst_file < 8; dst_rank--, dst_file++)
				{
					int square = dst_rank * 8 + dst_file;
					set_square(bishop_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
			}
			while (sub_mask != 0);
		}
	}
	for (int src_rank = 0; src_rank < 8; src_rank++)
	{
		for (int src_file = 0; src_file < 8; src_file++)
		{
			int src_square = src_rank * 8 + src_file;
			uint64_t mask_mask = rook_masks[src_square];
			uint64_t sub_mask = mask_mask + 1;
			do
			{
				sub_mask = (sub_mask - 1) & mask_mask;
				uint64_t hash = get_rook_index(src_square, sub_mask);
				for (int dst_file = src_file + 1; dst_file < 8; dst_file++)
				{
					int square = src_rank * 8 + dst_file;
					set_square(rook_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_file = src_file - 1; dst_file >= 0; dst_file--)
				{
					int square = src_rank * 8 + dst_file;
					set_square(rook_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_rank = src_rank + 1; dst_rank < 8; dst_rank++)
				{
					int square = dst_rank * 8 + src_file;
					set_square(rook_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
				for (int dst_rank = src_rank - 1; dst_rank >= 0; dst_rank--)
				{
					int square = dst_rank * 8 + src_file;
					set_square(rook_tables[src_square][hash], square);
					if (test_square(sub_mask, square))
					{
						break;
					}
				}
			}
			while (sub_mask != 0);
		}
	}
	return true;
}

inline const bool _bitmasks = init_bitmasks();
